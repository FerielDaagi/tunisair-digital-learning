// Icon component with consistent styling
export const Icon = ({ 
  name, 
  size = 20, 
  color = 'currentColor', 
  className = '',
  style = {},
  ...props 
}) => {
  const IconComponent = IconTheme[name];
  
  if (!IconComponent) {
    console.warn(`Icon "${name}" not found in IconTheme`);
    return null;
  }
  
  return (
    <IconComponent
      size={size}
      color={color}
      className={className}
      style={{
        flexShrink: 0,
        ...style
      }}
      {...props}
    />
  );
};

